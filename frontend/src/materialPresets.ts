/** 判断预设在哪类筛选下可见 */
export function appliesTo(p: { applies: string }, f: 'all' | 'image' | 'video' | 'common'): boolean {
  if (f === 'all') return true
  if (f === 'common') return p.applies === '通用'
  if (f === 'image') return p.applies === '图片' || p.applies === '图片/视频' || p.applies === '通用'
  return p.applies === '视频' || p.applies === '图片/视频' || p.applies === '通用'
}
